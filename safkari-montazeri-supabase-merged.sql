-- 2) نرمال‌سازی پلاک برای تطبیق ارقام فارسی/عربی و جداکننده‌ها
create or replace function public.race_norm_plate(v text)
returns text language sql immutable as $$
  select upper(regexp_replace(
    translate(coalesce(v,''), '۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩', '01234567890123456789'),
    '[^A-Za-z0-9آ-ی]', '', 'g'));
$$;

