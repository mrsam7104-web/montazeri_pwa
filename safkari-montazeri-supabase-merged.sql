drop function if exists public.claim_race_discount(text,text);
create function public.claim_race_discount(p_full_name text, p_plate text)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  normalized text;
  registered boolean := false;
  code text;
  claim_id bigint;
  car jsonb;
  cars_now jsonb;
begin
  if length(trim(coalesce(p_full_name,''))) < 2 or length(trim(coalesce(p_plate,''))) < 5 then
    return jsonb_build_object('ok',false,'message','نام یا پلاک معتبر نیست.');
  end if;
  normalized := public.race_norm_plate(p_plate);
  select exists (
    select 1 from public.workshop_state ws,
      jsonb_array_elements(coalesce(ws.cars,'[]'::jsonb)) c
    where ws.id=1 and public.race_norm_plate(c->>'plate') = normalized
  ) into registered;
  code := '—';
  if not registered then
    loop
      code := lpad(floor(random()*10000)::int::text,4,'0');
      exit when not exists (
        select 1 from public.workshop_state ws,
          jsonb_array_elements(coalesce(ws.cars,'[]'::jsonb)) c
        where ws.id=1 and c->>'trackingCode'=code
      );
    end loop;
  end if;
  insert into public.race_discount_claims(full_name,plate,tracking_code,is_registered,discount_percent)
  values (left(trim(p_full_name),100),left(trim(p_plate),30),code,registered,5)
  returning id into claim_id;

  -- پلاک جدید علاوه بر جدول درخواست‌ها، به فهرست خودروهای پنل مدیر اضافه می‌شود.
  if not registered then
    car := jsonb_build_object(
      'id','race-' || replace(gen_random_uuid()::text,'-',''),
      'plate',left(trim(p_plate),30), 'phone','', 'trackingCode',code,
      'model','ثبت‌نام ماشین‌بازی منتظری',
      'received',to_char(now() at time zone 'Asia/Tehran','YYYY-MM-DD'),
      'color','', 'notes','نام و نام خانوادگی: ' || left(trim(p_full_name),100) || E'\nثبت‌نام از طریق ماشین‌بازی منتظری؛ تخفیف ۵٪',
      'stage',0, 'damages','[]'::jsonb
    );
    select coalesce(cars,'[]'::jsonb) into cars_now from public.workshop_state where id=1 for update;
    update public.workshop_state
      set cars=coalesce(cars_now,'[]'::jsonb) || jsonb_build_array(car), updated_at=now()
      where id=1;
  end if;
  return jsonb_build_object('ok',true,'is_registered',registered,'tracking_code',code,'claim_id',claim_id,'discount_percent',5);
exception when others then
  return jsonb_build_object('ok',false,'message','ثبت انجام نشد؛ ساختار جدول workshop_state را بررسی کنید.');
end; $$;
revoke all on function public.claim_race_discount(text,text) from public;
grant execute on function public.claim_race_discount(text,text) to anon, authenticated;

-- 4) جستجوی مشتری با پلاک و موبایل (تابع قبلی حفظ شده)
create or replace function public.lookup_vehicle(p_plate text, p_phone text)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  row_car jsonb; wanted_plate text; wanted_phone text; got_plate text; got_phone text;
begin
  wanted_plate := regexp_replace(translate(lower(coalesce(p_plate,'')),'۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩','01234567890123456789'),'[[:space:]ـ-]','','g');
  wanted_phone := regexp_replace(translate(lower(coalesce(p_phone,'')),'۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩','01234567890123456789'),'[[:space:]ـ-]','','g');
  if wanted_plate='' or wanted_phone='' then return null; end if;
  for row_car in select value from public.workshop_state s, jsonb_array_elements(coalesce(s.cars,'[]'::jsonb)) as value where s.id=1 loop
    got_plate := regexp_replace(translate(lower(coalesce(row_car->>'plate','')),'۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩','01234567890123456789'),'[[:space:]ـ-]','','g');
    got_phone := regexp_replace(translate(lower(coalesce(row_car->>'phone','')),'۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩','01234567890123456789'),'[[:space:]ـ-]','','g');
    if got_plate=wanted_plate and got_phone=wanted_phone then return row_car; end if;
  end loop;
  return null;
end; $$;
revoke all on function public.lookup_vehicle(text,text) from public;
grant execute on function public.lookup_vehicle(text,text) to anon, authenticated;

-- جستجوی مشتری با پلاک + کد پیگیری چهاررقمی
create or replace function public.lookup_vehicle_by_code(p_plate text, p_code text)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  car jsonb; wanted_plate text; wanted_code text; stored_plate text; stored_code text;
begin
  wanted_plate := regexp_replace(translate(lower(coalesce(p_plate,'')),'۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩','01234567890123456789'),'[[:space:]ـ-]','','g');
  wanted_code := regexp_replace(translate(lower(coalesce(p_code,'')),'۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩','01234567890123456789'),'[[:space:]ـ-]','','g');
  if wanted_plate='' or wanted_code !~ '^[0-9]{4}$' then return null; end if;
  for car in select value from public.workshop_state s, jsonb_array_elements(coalesce(s.cars,'[]'::jsonb)) as value where s.id=1 loop
    stored_plate := regexp_replace(translate(lower(coalesce(car->>'plate','')),'۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩','01234567890123456789'),'[[:space:]ـ-]','','g');
    stored_code := regexp_replace(translate(lower(coalesce(car->>'trackingCode','')),'۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩','01234567890123456789'),'[[:space:]ـ-]','','g');
    if stored_plate=wanted_plate and stored_code=wanted_code then return car; end if;
  end loop;
  return null;
end; $$;
revoke all on function public.lookup_vehicle_by_code(text,text) from public;
grant execute on function public.lookup_vehicle_by_code(text,text) to anon, authenticated;

