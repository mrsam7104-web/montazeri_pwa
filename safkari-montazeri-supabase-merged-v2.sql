-- ثبت ۵٪ در امتیاز ۳۰۰۰؛ این تابع ثبت‌نام تکراری نمی‌خواهد و پلاک نمی‌گیرد.
create or replace function public.claim_race_discount(p_full_name text,p_phone text,p_score integer default 3000)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare customer jsonb; ph text:=public.site_normalize_phone(p_phone); n text:=trim(coalesce(p_full_name,'')); code text; claim_id bigint;
begin
  if p_score<3000 then return jsonb_build_object('ok',false,'message','جایزه در امتیاز ۳۰۰۰ فعال می‌شود.'); end if;
  customer:=public.register_site_customer(n,ph);
  if coalesce((customer->>'ok')::boolean,false)=false then return customer; end if;
  code:=customer->>'customer_code';
  insert into public.race_discount_claims(full_name,phone,customer_code,score,discount_percent)
  values(n,ph,code,p_score,5) returning id into claim_id;
  return jsonb_build_object('ok',true,'customer_code',code,'claim_id',claim_id,'discount_percent',5,'continue_game',true);
exception when others then return jsonb_build_object('ok',false,'message','ثبت جایزه انجام نشد؛ خطای پایگاه داده را بررسی کنید.');
end; $$;
revoke all on function public.claim_race_discount(text,text,integer) from public;
grant execute on function public.claim_race_discount(text,text,integer) to anon,authenticated;

