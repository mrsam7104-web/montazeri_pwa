create or replace function public.site_normalize_phone(v text)
returns text language sql immutable as $$
  select regexp_replace(translate(coalesce(v,''),'۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩','01234567890123456789'),'[^0-9]','','g');
$$;

create or replace function public.register_site_customer(p_full_name text, p_phone text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare n text:=trim(coalesce(p_full_name,'')); ph text:=public.site_normalize_phone(p_phone); existing public.site_customers%rowtype; code text; tries int:=0;
begin
  if length(n)<3 or length(n)>100 then return jsonb_build_object('ok',false,'message','نام و نام خانوادگی معتبر نیست.'); end if;
  if length(ph)=12 and left(ph,2)='98' then ph:='0'||right(ph,10); end if;
  if length(ph)<>11 or left(ph,2)<>'09' then return jsonb_build_object('ok',false,'message','شماره موبایل باید ۱۱ رقم و با 09 شروع شود.'); end if;
  select * into existing from public.site_customers where phone=ph;
  if found then
    update public.site_customers set full_name=n, updated_at=now() where phone=ph returning * into existing;
    return jsonb_build_object('ok',true,'customer_code',existing.customer_code,'full_name',existing.full_name,'phone',existing.phone,'existing',true);
  end if;
  loop
    tries:=tries+1;
    code:=upper(substr(encode(gen_random_bytes(6),'hex'),1,10));
    exit when not exists(select 1 from public.site_customers where customer_code=code);
    if tries>20 then raise exception 'code generation failed'; end if;
  end loop;
  insert into public.site_customers(full_name,phone,customer_code) values(n,ph,code) returning * into existing;
  return jsonb_build_object('ok',true,'customer_code',existing.customer_code,'full_name',existing.full_name,'phone',existing.phone,'existing',false);
exception when unique_violation then
  select * into existing from public.site_customers where phone=ph;
  if found then return jsonb_build_object('ok',true,'customer_code',existing.customer_code,'full_name',existing.full_name,'phone',existing.phone,'existing',true); end if;
  return jsonb_build_object('ok',false,'message','ثبت ناموفق بود؛ دوباره تلاش کنید.');
end; $$;
revoke all on function public.register_site_customer(text,text) from public;
grant execute on function public.register_site_customer(text,text) to anon,authenticated;

